def build_docker_image(
    context: AssetExecutionContext,
    env: dict,  # pylint: disable=redefined-outer-name
    docker_config_json: pathlib.Path,  # pylint: disable=redefined-outer-name
    group_in: dict,  # pylint: disable=redefined-outer-name
    docker_config: DockerConfig,  # pylint: disable=redefined-outer-name
    apt_packages: dict[str, list[str]],  # pylint: disable=redefined-outer-name
    pip_packages: list,  # pylint: disable=redefined-outer-name
) -> Generator[Output[dict] | AssetMaterialization, None, None]:
    """ """

    docker_image: dict = group_in["docker_image"]

    docker_file = pathlib.Path(
        env["DOT_LANDSCAPES"],
        env.get("LANDSCAPE", "default"),
        f"{ASSET_HEADER['group_name']}__{'__'.join(ASSET_HEADER['key_prefix'])}",
        "__".join(context.asset_key.path),
        "Dockerfiles",
        "Dockerfile",
    )

    docker_file.parent.mkdir(parents=True, exist_ok=True)

    #################################################

    (
        image_name,
        image_prefixes,
        tags,
        build_base_parent_image_prefix,
        build_base_parent_image_name,
        build_base_parent_image_tags,
    ) = get_image_metadata(
        context=context,
        docker_image=docker_image,
        docker_config=docker_config,
        env=env,
    )

    #################################################

    # @formatter:off
    files_10_2 = {
        "AWSPortalLink.run": env["INSTALLER_AWSPortalLink"],
        "DeadlineClient.run": env["INSTALLER_DeadlineClient"],
        "DeadlineRepository.run": env["INSTALLER_DeadlineRepository"],
    }
    # @formatter:on

    apt_install_str_deadline_10_2: str = get_apt_install_str(
        apt_install_packages=apt_packages["deadline_10_2"],
    )

    pip_install_str: str = get_pip_install_str(pip_install_packages=pip_packages)

    docker_payload = ".payload"
    tmpdir = docker_file.parent / docker_payload
    tmpdir.mkdir(exist_ok=True, parents=True)

    copy_str: str = get_copy_str(
        temp_dir=tmpdir,
        copy_packages=files_10_2,
        mode=755,
    )

    # @formatter:off
    docker_file_str = textwrap.dedent(
        """\
        # {auto_generated}
        # {dagster_url}
        FROM {parent_image} AS {image_name}
        LABEL authors="{AUTHOR}"

        SHELL ["/bin/bash", "-c"]

        RUN apt-get update && apt-get upgrade -y

        {apt_install_str_deadline_10_2}

        {pip_install_str}

        WORKDIR /installers

        {copy_str}

        # Todo:
        # RUN thinkbox-ssl-gen --help

        RUN apt-get clean

        ENTRYPOINT []
        """
    ).format(
        copy_str=copy_str,
        apt_install_str_deadline_10_2=apt_install_str_deadline_10_2,
        pip_install_str=pip_install_str.format(
            **env,
        ),
        auto_generated=f"AUTO-GENERATED by Dagster Asset {'__'.join(context.asset_key.path)}",
        dagster_url=urllib.parse.quote(
            f"http://localhost:3000/asset-groups/{'%2F'.join(context.asset_key.path)}",
            safe=":/%",
        ),
        image_name=image_name,
        # Todo: this won't work as expected if len(tags) > 1
        parent_image=f"{build_base_parent_image_prefix}{build_base_parent_image_name}:{build_base_parent_image_tags[0]}",
        **env,
    )
    # @formatter:on

    with open(docker_file, "w") as fw:
        fw.write(docker_file_str)

    with open(docker_file, "r") as fr:
        docker_file_content = fr.read()

    for key, value in files_10_2.items():
        if not pathlib.Path(value).exists():
            context.log.error(f"File {value} does not exist")
        context.log.debug(f"{value = }")
        context.log.debug(f"{pathlib.Path(tmpdir) / key = }")
        shutil.copyfile(
            src=value,
            dst=pathlib.Path(tmpdir) / key,
        )

    #################################################

    image_data, logs = create_image(
        context=context,
        image_name=image_name,
        image_prefixes=image_prefixes,
        tags=tags,
        docker_image=docker_image,
        docker_config=docker_config,
        docker_config_json=docker_config_json,
        docker_file=docker_file,
    )

    yield Output(image_data)

    yield AssetMaterialization(
        asset_key=context.asset_key,
        metadata={
            "__".join(context.asset_key.path): MetadataValue.json(image_data),
            "docker_file": MetadataValue.md(f"```shell\n{docker_file_content}\n```"),
            "env": MetadataValue.json(env),
            "logs": MetadataValue.json(logs),
        },
    )


