@asset(
    **ASSET_HEADER,
    ins={
        "env": AssetIn(
            AssetKey([*ASSET_HEADER["key_prefix"], "env"]),
        ),
        "deadline_command_install_repository": AssetIn(
            AssetKey(
                [*ASSET_HEADER["key_prefix"], "deadline_command_install_repository"]
            ),
        ),
    },
)
def deadline_script_install_repository(
    context: AssetExecutionContext,
    env: dict,  # pylint: disable=redefined-outer-name
    deadline_command_install_repository: list,  # pylint: disable=redefined-outer-name
) -> Generator[Output[pathlib.Path] | AssetMaterialization, None, None]:
    """ """

    install_repository = dict()

    install_repository["exe"] = shutil.which("bash")
    install_repository["script"] = str()

    # https://github.com/michimussato/kitsu-setup/blob/main/README_KITSU.md
    install_repository["script"] += "#!/bin/bash\n"
    install_repository["script"] += "\n"
    install_repository[
        "script"
    ] += "if [[ ! -z \"$( ls -A '/opt/Thinkbox/DeadlineRepository10')\" ]]; then\n"
    install_repository[
        "script"
    ] += "    echo /opt/Thinkbox/DeadlineRepository10 is not empty.\n"
    install_repository["script"] += "    echo Using existing Installation.\n"
    install_repository["script"] += "    echo Quit.\n"
    install_repository["script"] += "    exit 0;\n"
    install_repository["script"] += "fi\n"
    install_repository["script"] += "\n"
    install_repository[
        "script"
    ] += "echo /opt/Thinkbox/DeadlineRepository10 is empty or does not exist.\n"
    install_repository["script"] += "echo Installing Repository...\n"
    install_repository["script"] += "\n"
    install_repository[
        "script"
    ] += f"{shlex.join(deadline_command_install_repository)}\n"
    install_repository["script"] += "\n"
    install_repository["script"] += "echo Repository installed.\n"
    install_repository["script"] += "\n"
    install_repository["script"] += "exit 0\n"

    install_repository_script = pathlib.Path(
        env["DOT_LANDSCAPES"],
        env.get("LANDSCAPE", "default"),
        f"{ASSET_HEADER['group_name']}__{'__'.join(ASSET_HEADER['key_prefix'])}",
        "__".join(context.asset_key.path),
        "install_repository.sh",
    )

    install_repository_script.parent.mkdir(parents=True, exist_ok=True)

    with open(
        file=install_repository_script,
        mode="w",
    ) as sh_install_repository:
        sh_install_repository.write(install_repository["script"])

    yield Output(install_repository_script)

    yield AssetMaterialization(
        asset_key=context.asset_key,
        metadata={
            "__".join(context.asset_key.path): MetadataValue.path(
                install_repository_script
            ),
            "dict_install_repository": MetadataValue.json(install_repository),
            "script_install_repository": MetadataValue.md(
                f"```shell\n{install_repository['script']}\n```"
            ),
        },
    )


